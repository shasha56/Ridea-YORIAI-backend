alter table public.drivers enable row level security;
alter table public.cars enable row level security;
alter table public.shifts enable row level security;
alter table public.reservations enable row level security;

revoke all privileges on table public.users from public, anon, authenticated;
revoke all privileges on table public.drivers from public, anon, authenticated;
revoke all privileges on table public.cars from public, anon, authenticated;
revoke all privileges on table public.shifts from public, anon, authenticated;
revoke all privileges on table public.reservations from public, anon, authenticated;

grant usage on schema public to service_role;
grant select, insert, update, delete on table public.users to service_role;
grant select, insert, update, delete on table public.drivers to service_role;
grant select, insert, update, delete on table public.cars to service_role;
grant select, insert, update, delete on table public.shifts to service_role;
grant select, insert, update, delete on table public.reservations to service_role;

revoke all privileges on sequence public.drivers_id_seq from public, anon, authenticated;
revoke all privileges on sequence public.cars_id_seq from public, anon, authenticated;
revoke all privileges on sequence public.shifts_id_seq from public, anon, authenticated;
revoke all privileges on sequence public.reservations_id_seq from public, anon, authenticated;

grant usage, select on sequence public.drivers_id_seq to service_role;
grant usage, select on sequence public.cars_id_seq to service_role;
grant usage, select on sequence public.shifts_id_seq to service_role;
grant usage, select on sequence public.reservations_id_seq to service_role;

revoke execute on function public.set_updated_at() from public, anon, authenticated;
revoke execute on function public.enforce_shift_constraints() from public, anon, authenticated;
revoke execute on function public.rematch_reservations_after_shift_cancellation() from public, anon, authenticated;

commit;
